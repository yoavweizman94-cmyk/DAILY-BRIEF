# -*- coding: utf-8 -*-
"""מי ניתן לסקירה ומי נסקר מראש — שני כללים שונים, ובכוונה.

`reviewable` — **מה שהקורא רשאי ללחוץ עליו.** כל דיווח שיש לו קובץ.
זו רשימת ההיתר שה-Function אוכפת: הדפדפן שולח מזהה בלבד, והנתיב ל-PDF
נקרא מהמפה. הרחבתה לכל הדיווחים היא בקשה של יואב מ-27/08/2026.

`pregenerate` — **על מה משלמים מראש.** צר בהרבה: דוח כספי של חברת
כיסוי. סקירה מראש עולה בין אם מישהו יפתח אותה ובין אם לא, ולכן היא
שמורה למה שכמעט בוודאות ייקרא. השאר נוצר בלחיצה, ונשמר ב-KV כך
שהלחיצה השנייה חינם.

**הפרדת שני הכללים היא העיקר כאן.** כשהיה כלל אחד, הרחבת הכפתור
הייתה מרחיבה גם את ההוצאה מראש — פי כמה, בלי שאיש יבקש זאת.

המודול מכוון להיות חף מתלויות כבדות: `build.py` מייבא אותו בזמן
פריסה, שם `anthropic` אינו מותקן.
"""
from __future__ import annotations

# **סיווג לפי סוג המסמך, לא לפי כדאיות התשלום.** כשהיה כלל אחד, "מצגת"
# ו"תיקון" הוחרגו — נכון לשאלה "על מה משלמים מראש", שגוי לשאלה "באיזה
# מבנה לסקור": מצגת תוצאות מלאה במספרים, ותיקון לדוח רבעוני הוא עדיין
# דוח רבעוני. ההחרגות עברו ל-pregenerate, שם מקומן.
FINANCIAL = (
    "דוח רבעון", "דוח רבעוני", "דוח תקופתי", "דוחות כספיים", "דוח כספי",
    "דוח שנתי", "דוח חצי שנתי", "תוצאות כספיות", "תוצאות הרבעון",
    "מצגת משקיעים", "מצגת לשוק ההון",
    # טפסים זרים של חברות דואליות
    "financial statement", "quarterly report", "annual report",
    "6-k", "6k-", "20-f", "10-q", "10-k", "interim report",
)
# מסמכים שאינם דוח כספי גם כשהמילה "דוח" מופיעה בהם.
NOT_FINANCIAL = ("מצבת התחייבות", "iXBRL", "אסיפה")

# מה שלא משלמים עליו **מראש**, גם כשהוא דוח כספי: מצגת מלווה דוח,
# תיקון מגיע אחרי שהמקור כבר נסקר, והצגה מחדש היא גרסה של קיים.
NOT_WORTH_PREGEN = ("מצגת", "תיקון", "הצגה מחדש", "iXBRL")


def is_financial(title: str) -> bool:
    """האם המסמך הוא דוח כספי. **קובע את מבנה הסקירה.**

    שולי רווח, תזרים ומגזרים אינם רלוונטיים להודעה מיידית, ופרומפט
    שמבקש אותם על זימון אסיפה מחזיר סקירה מלאה ב"לא נמצא".
    """
    t = (title or "").lower()
    if any(x.lower() in t for x in NOT_FINANCIAL):
        return False
    return any(x.lower() in t for x in FINANCIAL)


def has_pdf(rec: dict) -> bool:
    p = rec.get("p")
    return bool(p) and p != "None"


def reviewable(rec: dict) -> bool:
    """כל דיווח שיש לו קובץ — עליו אפשר ללחוץ "סקירה"."""
    return has_pdf(rec)


def pregenerate(rec: dict) -> bool:
    """מה שנסקר מראש בתשלום: דוח כספי של חברת כיסוי, ולא מצגת או תיקון."""
    t = rec.get("t") or ""
    if any(x in t for x in NOT_WORTH_PREGEN):
        return False
    return (str(rec.get("cov")) == "1"
            and is_financial(t)
            and has_pdf(rec))
